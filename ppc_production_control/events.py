"""Doc-event handlers wired in hooks.py.

They only *tag*, *guard* and *notify*; heavy work is deferred to a deduplicated background job so a
Work Order submit (which creates all of its Job Cards) is never slowed down or broken by PPC.
"""

import frappe
from frappe import _
from frappe.utils import cint

from ppc_production_control.services.constants import PLAN_DT
from ppc_production_control.services.utils import enqueue_once, in_test


# ------------------------------------------------------------------------------ Production Plan
def production_plan_submitted(doc, method=None):
	"""After the standard plan is submitted, create its Work Orders as drafts (in the background)."""
	if not cint(doc.get("ppc_auto_create_work_orders")):
		return
	enqueue_once(
		"ppc_production_control.services.work_orders.create_draft_work_orders_job",
		job_id=f"ppc_create_wo::{doc.name}",
		queue="long",
		timeout=3600,
		plan=doc.name,
	)


def sales_order_validate(doc, method=None):
	"""Check each line's machine preference on the server and keep its estimates and status current."""
	from ppc_production_control.services import recommend

	for row in doc.get("items") or []:
		recommend.validate_line(row, doc)


def production_plan_validate(doc, method=None):
	"""Carry the Sales Order lines' machine preferences onto the plan's items (the link is the line's name)."""
	from ppc_production_control.services import recommend

	recommend.copy_preferences_to_plan(doc)


def work_order_apply_machine_plan(doc, method=None):
	"""Use the Sales Order's preferred machines on a new Work Order's operations, after re-checking them now. A failure here never blocks the Work Order."""
	from ppc_production_control.services import recommend

	try:
		doc.flags.ppc_machine_result = recommend.apply_to_work_order(doc)
	except Exception:
		doc.flags.ppc_machine_result = None
		frappe.log_error(title="PPC: applying the preferred machines failed", message=frappe.get_traceback())


def work_order_notify_machine_plan(doc, method=None):
	"""Once the Work Order exists: audit what was applied, and tell the planner about machines that could not be used."""
	result = doc.flags.get("ppc_machine_result")
	if not result:
		return
	from ppc_production_control.services import recommend

	try:
		recommend.notify_unavailable(doc, result)
	except Exception:
		frappe.log_error(title="PPC: notifying about the machine plan failed", message=frappe.get_traceback())


def work_order_before_insert(doc, method=None):
	"""Duplicate guard. The standard 'Work Order / Subcontract PO' button keeps offering the same
	rows until their Work Orders are *submitted*, so a second click would create duplicates. For plans
	that use PPC auto-creation a row can have only one live Work Order."""
	work_order_apply_machine_plan(doc)
	if not doc.get("production_plan"):
		return
	if doc.get("production_plan_item"):
		key = {"production_plan_item": doc.production_plan_item}
	elif doc.get("production_plan_sub_assembly_item"):
		key = {"production_plan_sub_assembly_item": doc.production_plan_sub_assembly_item}
	else:
		return
	if not cint(frappe.db.get_value(PLAN_DT, doc.production_plan, "ppc_auto_create_work_orders")):
		return
	existing = frappe.db.get_value(
		"Work Order", {"production_plan": doc.production_plan, "docstatus": ["<", 2], **key}, "name"
	)
	if existing:
		frappe.throw(
			_("Work Order {0} already exists for this Production Plan item. Open it from the plan's connections.").format(existing),
			title=_("Duplicate Work Order prevented"),
		)


# ------------------------------------------------------------------------------ Job Card
def job_card_before_insert(doc, method=None):
	"""Tag Job Cards generated by ERPNext (on Work Order submit) with the owning Production Plan."""
	if doc.get("ppc_production_plan") or not doc.get("work_order"):
		return
	plan = frappe.db.get_value("Work Order", doc.work_order, "production_plan")
	if plan:
		doc.ppc_production_plan = plan


def job_card_after_insert(doc, method=None):
	"""Capture the immutable baseline (revision 0) the moment a Job Card first gets a schedule.

	A failure here must never break the Work Order submit that is creating the card: it is logged and
	the card simply shows up under "missing baseline" for the reconciliation tools."""
	if doc.get("ppc_production_plan") and doc.get("expected_start_date") and doc.get("expected_end_date"):
		try:
			from ppc_production_control.services import revisions
			from ppc_production_control.services.utils import savepoint

			with savepoint():
				revisions.capture_baseline(doc.name, revisions.BASELINE_CREATED)
		except Exception:
			frappe.log_error(title="PPC: baseline capture failed", message=frappe.get_traceback())
	_queue_refresh(doc.get("ppc_production_plan"))


def job_card_validate(doc, method=None):
	"""The baseline is immutable: once recorded, no save may change it."""
	if doc.is_new() or frappe.flags.get("ppc_baseline_write"):
		return
	before = doc.get_doc_before_save()
	if not before or not before.get("ppc_original_start"):
		return
	if (
		doc.get("ppc_original_start") != before.get("ppc_original_start")
		or doc.get("ppc_original_end") != before.get("ppc_original_end")
	):
		frappe.throw(
			_("The original schedule of a Job Card is a recorded baseline and cannot be changed."),
			frappe.PermissionError,
		)


def job_card_changed(doc, method=None):
	_queue_refresh(doc.get("ppc_production_plan"))


def work_order_changed(doc, method=None):
	_queue_refresh(doc.get("production_plan"))


def _queue_refresh(plan: str | None):
	if not plan or in_test() or frappe.flags.get("ppc_in_sync"):
		return
	enqueue_once(
		"ppc_production_control.services.sync.refresh_plan_job",
		job_id=f"ppc_refresh::{plan}",
		queue="short",
		timeout=600,
		plan=plan,
	)
