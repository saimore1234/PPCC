"""Doc-event handlers wired in hooks.py.

They only *tag*, *guard* and *notify*; heavy work is deferred to a deduplicated background job so a
Work Order submit (which creates all of its Job Cards) is never slowed down or broken by PPC.
"""

import frappe
from frappe import _
from frappe.utils import cint

from ppc_production_control.services.constants import PLAN_DT
from ppc_production_control.services.utils import enqueue_once, in_test


# ------------------------------------------------------------------------------ Production Plan
def production_plan_submitted(doc, method=None):
	"""After the standard plan is submitted, create its Work Orders as drafts (in the background)."""
	if not cint(doc.get("ppc_auto_create_work_orders")):
		return
	enqueue_once(
		"ppc_production_control.services.work_orders.create_draft_work_orders_job",
		job_id=f"ppc_create_wo::{doc.name}",
		queue="long",
		timeout=3600,
		plan=doc.name,
	)


def work_order_before_insert(doc, method=None):
	"""Duplicate guard. The standard 'Work Order / Subcontract PO' button keeps offering the same
	rows until their Work Orders are *submitted*, so a second click would create duplicates. For plans
	that use PPC auto-creation a row can have only one live Work Order."""
	if not doc.get("production_plan"):
		return
	if doc.get("production_plan_item"):
		key = {"production_plan_item": doc.production_plan_item}
	elif doc.get("production_plan_sub_assembly_item"):
		key = {"production_plan_sub_assembly_item": doc.production_plan_sub_assembly_item}
	else:
		return
	if not cint(frappe.db.get_value(PLAN_DT, doc.production_plan, "ppc_auto_create_work_orders")):
		return
	existing = frappe.db.get_value(
		"Work Order", {"production_plan": doc.production_plan, "docstatus": ["<", 2], **key}, "name"
	)
	if existing:
		frappe.throw(
			_("Work Order {0} already exists for this Production Plan item. Open it from the plan's connections.").format(existing),
			title=_("Duplicate Work Order prevented"),
		)


# ------------------------------------------------------------------------------ Job Card
def job_card_before_insert(doc, method=None):
	"""Tag Job Cards generated by ERPNext (on Work Order submit) with the owning Production Plan."""
	if doc.get("ppc_production_plan") or not doc.get("work_order"):
		return
	plan = frappe.db.get_value("Work Order", doc.work_order, "production_plan")
	if plan:
		doc.ppc_production_plan = plan


def job_card_after_insert(doc, method=None):
	"""Remember the first schedule ERPNext gave the card, so 'original' vs 'revised' is meaningful."""
	if doc.get("expected_start_date") and doc.get("expected_end_date") and not doc.get("ppc_original_start"):
		frappe.db.set_value(
			"Job Card",
			doc.name,
			{"ppc_original_start": doc.expected_start_date, "ppc_original_end": doc.expected_end_date},
			update_modified=False,
		)
	_queue_refresh(doc.get("ppc_production_plan"))


def job_card_changed(doc, method=None):
	_queue_refresh(doc.get("ppc_production_plan"))


def work_order_changed(doc, method=None):
	_queue_refresh(doc.get("production_plan"))


def _queue_refresh(plan: str | None):
	if not plan or in_test() or frappe.flags.get("ppc_in_sync"):
		return
	enqueue_once(
		"ppc_production_control.services.sync.refresh_plan_job",
		job_id=f"ppc_refresh::{plan}",
		queue="short",
		timeout=600,
		plan=plan,
	)
